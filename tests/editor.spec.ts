import { test, expect } from '@playwright/test';

test('furniture editing, room finishes, saving, and mobile layout', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('canvas')).toBeVisible();
  await page.getByRole('button', { name: 'Add Lounge Chair' }).click();
  await expect(page.locator('.selection-heading strong')).toHaveText('Lounge Chair');
  await page.getByRole('button', { name: 'Rotate', exact: true }).click();
  await page.getByRole('button', { name: 'Increase furniture size' }).click();
  await page.getByRole('button', { name: 'Furniture color #6d7b6c' }).click();
  await page.getByRole('button', { name: 'Duplicate', exact: true }).click();
  await page.getByRole('button', { name: 'Remove', exact: true }).click();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.locator('.selection-heading strong')).toHaveText('Lounge Chair');
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await page.getByRole('button', { name: 'Room', exact: true }).click();
  await page.getByLabel('Wall color #ccd3c5').click();
  await page.getByLabel('Floor color #9f7956').click();
  await page.getByRole('button', { name: 'Golden hour Warm & cozy' }).click();
  await page.getByRole('button', { name: 'Show dimensions and floor grid' }).click();
  await page.getByRole('button', { name: 'Top view', exact: true }).click();
  await page.getByRole('button', { name: '3D view', exact: true }).click();
  await page.getByRole('button', { name: 'Save design', exact: true }).click();
  await page.getByRole('button', { name: 'My designs', exact: true }).click();
  await page.getByLabel('New design name').fill('Test retreat');
  await page.getByRole('button', { name: 'Save current room' }).click();
  await expect(page.locator('.saved-card').filter({ hasText: 'Test retreat' })).toHaveCount(1);
  await page.getByRole('button', { name: 'Close saved designs' }).click();
  await page.waitForTimeout(600);
  await page.reload();
  await page.getByRole('button', { name: 'Room', exact: true }).click();
  await expect(page.getByLabel('Wall color #ccd3c5')).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: 'Furniture', exact: true }).click();
  await page.screenshot({ path: 'artifacts/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'artifacts/mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Add furniture', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Add Cloud Sofa' })).toBeVisible();
  await page.getByRole('button', { name: 'Close furniture library' }).click();
  await expect(page.getByRole('button', { name: 'Add Cloud Sofa' })).toBeHidden();
  const hasOverflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  expect(hasOverflow).toBe(false);
  expect(errors).toEqual([]);
});
